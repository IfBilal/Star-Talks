#!/usr/bin/env python3
"""Build supabase/functions/_shared/tarot-waite.ts from A.E. Waite's *The Pictorial Key to the Tarot*, Part III.
Source text: English Wikisource transcription of the 1910/1911 edition (public domain; Waite d. 1942).
Usage: build-tarot-waite.py <part3.txt> <out.ts>
Get part3.txt: fetch https://en.wikisource.org/w/api.php?action=parse&page=The_Pictorial_Key_to_the_Tarot/Part_3&prop=text&format=json&formatversion=2
and convert the HTML in .parse.text to plain text (strip tags, zero-width and soft-hyphen characters, one paragraph per line)."""
import re, sys, json
src = open(sys.argv[1]).read()
slug = lambda s: re.sub(r'(^-|-$)', '', re.sub(r'[^a-z0-9]+', '-', s.lower()))
clean = lambda s: re.sub(r'\s+', ' ', s).strip()
def split(text):
    # Waite's text has one typo ("Reversed;" for Four of Pentacles).
    parts = re.split(r'Reversed[:;]', text, maxsplit=1)
    up = parts[0]; rev = parts[1] if len(parts) > 1 else ''
    return clean(up.replace('Divinatory Meanings:', '')), clean(rev)

cards = {}
# ---- Major Arcana: "N. Name.—upright... Reversed: ..." (Fool is "Zero. The Fool.—")
major_order = ['The Fool','The Magician','The High Priestess','The Empress','The Emperor','The Hierophant','The Lovers','The Chariot','Strength','The Hermit','Wheel of Fortune','Justice','The Hanged Man','Death','Temperance','The Devil','The Tower','The Star','The Moon','The Sun','Judgement','The World']
for m in re.finditer(r'(?m)^(Zero|\d{1,2})\. ([^\n]{3,40}?)\.—(.*)$', src):
    n = 0 if m.group(1) == 'Zero' else int(m.group(1))
    if n > 21: continue
    name = major_order[n]; up, rev = split(m.group(3))
    cards[slug(name)] = dict(id=slug(name), name=name, section='Part III, The Greater Arcana and their Divinatory Meanings', waiteName=m.group(2), upright=up, reversed=rev)

# ---- Minor Arcana: suit heading, then rank line, then paragraphs containing "Divinatory Meanings:" ... "Reversed:"
ranks = ['Ace','Two','Three','Four','Five','Six','Seven','Eight','Nine','Ten','Page','Knight','Queen','King']
suit = None; cur = None; buf = []
def flush():
    global cur, buf
    if cur and buf:
        text = ' '.join(buf)
        if 'Divinatory Meanings:' in text:
            body = text.split('Divinatory Meanings:', 1)[1]
            up, rev = split(body)
            name = f'{cur[1]} of {cur[0]}'
            cards[slug(name)] = dict(id=slug(name), name=name, section=f'Part III, The Suit of {cur[0]}', waiteName=name, upright=up, reversed=rev)
    cur, buf = None, []
for line in src.split('\n'):
    s = line.strip()
    m = re.match(r'THE SUIT OF (WANDS|CUPS|SWORDS|PENTACLES)$', s)
    if m: flush(); suit = m.group(1).title(); continue
    if s.startswith('THE GREATER ARCANA'): flush(); suit = None; continue
    if suit and s in ranks: flush(); cur = (suit, s); continue
    if suit and s.upper() == suit.upper(): continue
    if cur: buf.append(s)
flush()

suits = ['Wands','Cups','Swords','Pentacles']
expected = [slug(n) for n in major_order] + [slug(f'{r} of {s}') for s in suits for r in ranks]
NO_REVERSED_IN_SOURCE = {'two-of-cups'}  # Waite gives no reversed meaning for this card
missing = [e for e in expected if e not in cards or not cards[e]['upright'] or (not cards[e]['reversed'] and e not in NO_REVERSED_IN_SOURCE)]
print(f'cards parsed: {len(cards)}/78; missing or incomplete: {missing}', file=sys.stderr)
ordered = [cards[e] for e in expected if e in cards]
header = '''// Generated by scripts/data/build-tarot-waite.py - do not edit by hand.
// Source: A.E. Waite, The Pictorial Key to the Tarot (W. Rider & Son, 1910/1911), Part III, divinatory meanings.
// Text taken from the English Wikisource transcription. Public domain (published before 1923; Waite d. 1942).
// Upright/reversed strings are Waite's own wording, verbatim.
export const WAITE_SOURCE = 'A.E. Waite, The Pictorial Key to the Tarot (1910/1911)';
export const WAITE_RULES_VERSION = 'waite-pkt-1911/1.0.0';
export type WaiteCard = { id: string; name: string; section: string; waiteName: string; upright: string; reversed: string };
export const WAITE_CARDS: Record<string, WaiteCard> = '''
open(sys.argv[2], 'w').write(header + json.dumps({c['id']: c for c in ordered}, indent=1, ensure_ascii=False) + ';\n')
